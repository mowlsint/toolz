'use strict';
const assert=require('node:assert/strict');
const C=require('../wl-core.js');
const E=require('../wl-edit.js');
const de=C.normalizeInput({filename:'zeitung.pdf',title:'Deutsche Meldung',text:'Die Behörden meldeten eine neue Maßnahme im Hafen.',type:'pdf_column_candidate',page:3,section:'Spalte 1/3',published_date:'2026-11-06',source_name:'Testzeitung'});
const en=C.normalizeInput({filename:'alerts.msg',title:'Authorities announced a new control',text:'The authorities say the operation starts on November 12. The date remains uncertain.',source_name:'Test alert',reported_at:'2026-11-06T09:00:00Z'});
de.original_language='de';en.original_language='en';
en.translation_de={title:'Neue Kontrollen angekündigt',text:'Die Behörden kündigten neue Kontrollen an.',method:'external_manual_paste',status:'external_unreviewed',reviewed:false};
const md=C.asMarkdown([en,de]);
assert(md.startsWith('<!-- WL_FORMAT: mowlsint.white_lightning.markdown.v1 -->'));
assert(md.indexOf('## Abschnitt A')<md.indexOf('## Abschnitt B'));
assert(md.indexOf('### Deutsche Meldung')<md.indexOf('## Abschnitt B'));
assert(md.indexOf('### Neue Kontrollen angekündigt')<md.indexOf('## Abschnitt B'));
assert(md.indexOf('### Authorities announced a new control')>md.indexOf('## Abschnitt B'));
assert.equal((md.match(new RegExp(`WL_RECORD_START id="${en.id}"`,'g'))||[]).length,2);
assert(md.includes('[EREIGNISDATUM NICHT ERMITTELT]'),'Fehlende Ereignisdaten bleiben Platzhalter');
assert(md.includes('Ereignisdatum — Status:** partial'),'Teil-Datum bleibt als partial markiert');
assert(md.includes('2026-11-06'),'Belegtes Veröffentlichungsdatum bleibt erhalten');
assert(md.includes('extern eingefügt, ungeprüft'),'Übersetzung bleibt ungeprüft');
assert(md.includes('#### Originalinhalt (bereinigt)'),'Originaltext unverändert im Markdown-Fence');
assert(C.asMarkdown([de],{includeContent:false}).includes('Meldungs-ID'),'Metadaten bleiben auch ohne Volltext');
assert(!C.asMarkdown([de],{includeContent:false}).includes('```text'),'Ohne Volltext keine Inhalt-Fences');
const ticks=C.normalizeInput({title:'Titel',text:'Text mit ``` dreifachen Backticks und einer vierfachen ````, plus Abschluss.'});ticks.original_language='de';
assert(C.asMarkdown([ticks]).includes('`````text'),'Bei Code-Fences im Quelltext ausweichende Markdown-Fence verwenden');
const raw=C.normalizeInput({title:'Zwei Artikel',text:'Anfangsabschnitt mit ausreichendem Text.\n[[WL-TRENNEN]]\nZweiter Abschnitt mit ausreichendem Text.',filename:'zeitung.pdf',page:2,reported_at:'2026-11-06T12:30:00Z'});
raw.original_language='de';raw.event_date=C.dateObj('2026-11-05','known','manuell eingegeben');
const [a,b]=E.splitRecord(raw);
assert.equal(a.text,'Anfangsabschnitt mit ausreichendem Text.');
assert.equal(b.text,'Zweiter Abschnitt mit ausreichendem Text.');
assert.notEqual(a.id,b.id);assert.notEqual(a.id,raw.id);
assert.equal(a.report_date.value,'2026-11-06');assert.equal(a.event_date.value,null);assert.equal(a.event_date.review_required,true);
assert.equal(a.source_origins[0].id,raw.id);assert.equal(b.derived_from_ids.includes(raw.id),true);
assert.throws(()=>E.splitRecord({...raw,text:'Kein Trennmarker'}),/Trennmarker|WL-TRENNEN|eigene Zeile/);
assert.throws(()=>E.splitRecord({...raw,text:'A\n[[WL-TRENNEN]]\nB'}),/mindestens fünf Zeichen/);
const b2={...b,report_date:C.dateObj('2026-11-07','known','zweite Meldung'),source_page:3,source_file:'zeitung.pdf'};
assert(E.canMerge(a,b2));
const merged=E.mergeRecords(a,b2);
assert(merged.id!==a.id&&merged.id!==b2.id);
assert(merged.text.includes('Anfangsabschnitt')&&merged.text.includes('Zweiter Abschnitt'));
assert.equal(merged.report_date.status,'ambiguous','Datumswiderspruch bleibt offen');
assert.equal(merged.report_date.value,null,'Kein stillschweigendes Datumsüberschreiben');
assert.equal(merged.source_origins.length,2);
assert.equal(merged.source_page,2);assert.equal(merged.source_page_end,3);
assert(merged.derived_from_ids.includes(raw.id));
assert(!E.canMerge(a,{...b2,source_file:'andere_datei.pdf'}),'Keine unabsichtliche quellübergreifende Zusammenführung');
assert(!E.canMerge(a,{...b2,original_language:'en'}),'Nicht Deutsch und Englisch vermischen');
assert(!E.canMerge(a,{...b2,record_kind:'document_context'}),'Keine Dokumentkopf-Meldungsmischung');
assert(!E.canMerge(a,{...b2,translation_de:en.translation_de}),'Keine stille Löschung vorhandener Übersetzungen');
console.log('EDITOR/EXPORT TESTS OK — bilingual Markdown, date contract, provenance, split and merge');